#!/usr/bin/env python3
"""Cut the Holden take into one clip per line and write assets/cues.js (film-time word cues).

Word onsets come from whisper.cpp DTW token times (assets/audio/vo-src/words.json) minus a fixed lead,
cross-checked against silencedetect pauses. Run from the project root: python3 tools/make-cues.py
"""
import json, subprocess, os

SRC = "assets/audio/vo-src/holden-take1.mp3"
# (id, src_in, src_out, film_start)
CLIPS = [
    ("L1", 0.00, 6.85, 0.60),
    ("L2", 7.45, 14.15, 7.95),
    ("L3", 14.35, 20.95, 14.95),
    ("L4", 21.25, 30.15, 22.45),
    ("L5", 30.30, 39.60, 32.85),
    ("L6", 39.75, 43.30, 43.05),
    ("L7", 43.45, 48.666, 47.15),
]
END = 55.5
LEAD = 0.15  # DTW time sits ~0.1–0.25 s after the audible onset

words = json.load(open("assets/audio/vo-src/words.json"))

def film(t_src):
    for cid, a, b, s in CLIPS:
        if a <= t_src <= b:
            return round(t_src - a + s, 3)
    raise ValueError(t_src)

# key -> (word text, occurrence index in take)
KEYS = {
    "batiment": ("bâtiment,", 0), "artisanat": ("l'artisanat", 0), "industrie": ("l'industrie,", 0),
    "talent": ("talent", 0), "cv1": ("CV,", 0), "voit": ("voit", 0), "terrain": ("terrain.", 0),
    "manoo1": ("Manu,", 0), "reseau": ("réseau", 0), "social": ("social", 0), "metiers": ("métiers", 0),
    "manuels": ("manuels,", 0), "portfolio1": ("portfolio", 0), "numerique": ("numérique", 0),
    "montrer": ("montrer", 0), "savoirfaire": ("savoir-faire.", 0),
    "artisans": ("Artisan,", 0), "apprentis": ("apprenti,", 0), "entreprises": ("entreprise,", 0),
    "ecoles": ("école", 0), "cfa": ("CFA,", 0), "chacun": ("chacun", 0), "cree": ("crée", 0), "profil": ("profil.", 0),
    "jules": ("Jules,", 0), "apprenti": ("apprenti", 0), "metallier": ("métallier,", 0), "termine": ("termine", 0),
    "portail": ("portail.", 0), "prend": ("prend", 0), "photo": ("photo,", 0), "ajoute": ("l'ajoute", 0),
    "portfolio2": ("portfolio", 1), "partage": ("partage", 0), "tout": ("tout", 0), "reseau2": ("réseau.", 0),
    "entreprise": ("Côté-entreprise,", 0), "atelier": ("atelier", 0), "cherche": ("cherche", 0),
    "metallier2": ("métallier", 0), "rennes": ("Rennes,", 0), "filtre": ("filtre", 0), "metier": ("métier,", 0),
    "decouvre": ("découvre", 0), "portail2": ("portail", 0), "jules2": ("Jules", 0), "ecrit": ("écrit", 0),
    "directement": ("directement.", 0),
    "pas": ("Pas", 0), "besoin": ("besoin", 0), "cv2": ("CV,", 1), "travail": ("travail", 0), "parle": ("parlé", 0),
    "lui": ("lui.", 0),
    "manoo2": ("Manu,", 1), "revolution": ("révolution", 0), "regard": ("regard,", 0), "rejoignez": ("rejoignez", 0),
    "reseau3": ("réseau", 1), "site": ("manu.fr", 0),
}

cues = {}
for key, (txt, occ) in KEYS.items():
    hits = [w for w in words if w["w"] == txt]
    w = hits[occ]
    t = (w["dtw"] if w["dtw"] is not None else w["a"]) - LEAD
    cues[key] = film(max(t, w["a"] - 0.05))

os.makedirs("assets/audio/vo", exist_ok=True)
for cid, a, b, s in CLIPS:
    out = f"assets/audio/vo/{cid}.wav"
    subprocess.run(["ffmpeg", "-v", "error", "-y", "-ss", f"{a}", "-to", f"{b}", "-i", SRC,
                    "-af", "afade=t=in:st=0:d=0.02,areverse,afade=t=in:st=0:d=0.06,areverse",
                    "-ar", "48000", "-ac", "1", out], check=True)

clips = {cid: [s, a, b] for cid, a, b, s in CLIPS}
with open("assets/cues.js", "w") as f:
    f.write("// Generated by tools/make-cues.py — film-time cues from the Holden take (do not edit by hand).\n")
    f.write("window.CUES = " + json.dumps({"END": END, "clips": clips, **cues}, indent=1, ensure_ascii=False) + ";\n")
print(json.dumps(cues, indent=0))
